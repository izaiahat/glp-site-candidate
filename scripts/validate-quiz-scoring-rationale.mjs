// The rationale doc and the ranking code must say the same thing, forever.
//
// A weights file that drifts from the argument written beside it is worse than
// no argument at all: the next person reads a defence of weights that are no
// longer in force. This validator makes that state unbuildable. It also holds
// the per-provider unreachable rulings to the LIVE audit, so a ruling cannot
// outlive the fact it was a ruling about.
//
// Exit 0 = PASS, 1 = violations. Read-only; no network.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DEFAULT_PROFILE, GOAL_WEIGHT_PROFILES } from "../src/quiz-ranking.mjs";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const violations = [];
const fail = (code, detail) => violations.push({ code, ...detail });

const rationale = JSON.parse(await readFile(path.join(ROOT, "data/quiz-scoring-rationale.json"), "utf8"));
const quizConfig = JSON.parse(await readFile(path.join(ROOT, "data/quiz-config.json"), "utf8"));

if (rationale.schema !== "glp-quiz-scoring-rationale-v1") fail("rationale_schema_invalid", { got: rationale.schema });

// ---- 1. every weight in the doc equals the weight in force --------------
const documented = rationale.profiles || {};
const inForce = { default: DEFAULT_PROFILE, ...GOAL_WEIGHT_PROFILES };
for (const [name, profile] of Object.entries(inForce)) {
  const claimed = documented[name]?.weights;
  if (!claimed) { fail("profile_undocumented", { profile: name }); continue; }
  if (JSON.stringify(claimed) !== JSON.stringify(profile)) {
    fail("profile_weights_drifted", { profile: name, documented: claimed, in_force: profile });
  }
  if (String(documented[name]?.why || "").trim().length < 60) {
    fail("profile_why_too_thin", { profile: name, why: "a weight without an argument is a number nobody can defend" });
  }
}
for (const name of Object.keys(documented)) {
  if (!inForce[name]) fail("profile_documented_but_not_in_force", { profile: name });
}
// The goal answers a reader can actually give must all have a profile documented.
for (const option of (quizConfig.questions || []).find((q) => q.id === "goal")?.options || []) {
  if (!documented[option.value]) fail("goal_option_without_documented_profile", { goal: option.value });
}

// ---- 2. every dimension the weights use is defined in the doc ------------
const definedDimensions = new Set(Object.keys(rationale.dimensions || {}));
for (const [name, profile] of Object.entries(inForce)) {
  for (const dimension of Object.keys(profile)) {
    if (!definedDimensions.has(dimension)) fail("dimension_undefined", { profile: name, dimension });
  }
}

// ---- 3. rulings match the live audit's unreachable set -------------------
// The audit report is regenerated by `npm run audit:quiz` on the built tree, so
// this comparison is against what the reader is actually served.
const rulings = rationale.unreachable_rulings?.providers || {};
let audited = null;
try {
  const built = await readFile(path.join(ROOT, "public/quiz/provider-fit/index.html"), "utf8");
  const match = /<script type="application\/json" id="candidate-data">([\s\S]*?)<\/script>/.exec(built);
  const candidates = JSON.parse(match[1].replaceAll("\\u003c", "<"));
  const { orderCandidates } = await import("../src/quiz-ranking.mjs");
  const rankingMatch = /<script type="application\/json" id="quiz-ranking">([\s\S]*?)<\/script>/.exec(built);
  const cohortMin = JSON.parse(rankingMatch[1].replaceAll("\\u003c", "<")).cohort_min_6mo_usd;
  const states = JSON.parse(await readFile(path.join(ROOT, "scripts/quiz-audit-states.json"), "utf8"));
  const values = (id) => [null, ...((quizConfig.questions || []).find((q) => q.id === id)?.options || []).map((o) => o.value)];
  const reachable = new Set();
  for (const goal of values("goal")) {
    for (const insurance of values("insurance")) {
      for (const preference of values("medication_preference")) {
        for (const state of [null, ...states]) {
          const answers = {};
          if (goal) answers.goal = goal;
          if (insurance) answers.insurance = insurance;
          if (preference) answers.medication_preference = preference;
          if (state) answers.state = state;
          const pool = candidates.filter((candidate) => {
            if (answers.state && (candidate.excluded_states || []).includes(answers.state)) return false;
            if (preference && preference !== "not_sure" && !(candidate.therapeutic_tags || []).includes(preference)) return false;
            return Object.entries(candidate.rules || {}).every(([q, allowed]) => !answers[q] || allowed.includes(answers[q]));
          });
          for (const row of orderCandidates(pool, goal, preference, cohortMin)) reachable.add(row.program_id);
        }
      }
    }
  }
  audited = candidates.filter((c) => !reachable.has(c.program_id)).map((c) => c.program_id).sort();
} catch (error) {
  fail("built_quiz_unreadable", { why: String(error.message || error) });
}

if (audited) {
  for (const id of audited) {
    const ruling = rulings[id];
    if (!ruling) { fail("unreachable_provider_without_ruling", { program_id: id, why: "an unreachable provider with no written ruling is an unexplained silence" }); continue; }
    if (!["legitimately_outranked", "legitimately_outranked_and_evidence_gap"].includes(ruling.ruling)) {
      fail("ruling_verdict_invalid", { program_id: id, ruling: ruling.ruling });
    }
    if (String(ruling.why || "").trim().length < 80) fail("ruling_why_too_thin", { program_id: id });
    if (String(ruling.what_would_change_it || "").trim().length < 20) fail("ruling_without_remedy", { program_id: id, why: "a ruling must name the evidence that would overturn it" });
    if (!Number.isInteger(ruling.best_achievable_rank) || ruling.best_achievable_rank < 4) {
      fail("ruling_rank_implausible", { program_id: id, best_achievable_rank: ruling.best_achievable_rank });
    }
  }
  for (const id of Object.keys(rulings)) {
    if (!audited.includes(id)) fail("ruling_for_a_now_reachable_provider", { program_id: id, why: "the ruling has outlived the fact; delete it or restate it" });
  }
}

// ---- 4. every golden vector carries a written rationale ------------------
for (const vector of quizConfig.golden_vectors || []) {
  if (String(vector.rationale || "").trim().length < 40) {
    fail("golden_vector_without_rationale", { vector_id: vector.vector_id, why: "a golden vector that changed without a written reason is a silently loosened test" });
  }
}

const report = {
  schema: "glp-quiz-scoring-rationale-validation-v1",
  profiles_checked: Object.keys(inForce).length,
  unreachable_audited: audited,
  rulings_written: Object.keys(rulings).length,
  golden_vectors: (quizConfig.golden_vectors || []).length,
  violations,
  status: violations.length ? "VIOLATIONS" : "PASS",
};
process.stdout.write(JSON.stringify(report, null, 2) + "\n");
process.exit(violations.length ? 1 : 0);

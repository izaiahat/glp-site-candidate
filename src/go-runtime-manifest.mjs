import { createHash } from "node:crypto";

export function manifestJsonText(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function manifestSha256(manifest) {
  return createHash("sha256").update(manifestJsonText(manifest)).digest("hex");
}

export function renderGoRuntimeManifestModule(manifest) {
  const programs = Object.fromEntries((manifest.programs || []).map((entry) => [entry.route_slug || entry.program_id, entry]));
  const payload = {
    schema: manifest.schema,
    program_registry_schema: manifest.program_registry_schema,
    site_profile: manifest.site_profile,
    internal_fallback: manifest.internal_fallback,
    manifest_sha256: manifestSha256(manifest),
    programs,
  };
  return `// Generated by scripts/build-staging.mjs. Do not edit by hand.\nexport const GO_RUNTIME_MANIFEST = Object.freeze(${JSON.stringify(payload, null, 2)});\n`;
}
